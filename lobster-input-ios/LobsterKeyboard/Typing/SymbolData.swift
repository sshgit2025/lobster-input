import Foundation

/// 分类符号板数据(对齐搜狗/百度/Gboard 符号面板课题调研结论):
/// 最近/中文/英文/括号/数学/序号/货币/箭头。数据经 scratch-keyboard-verify/test_symbols.py 验证
/// (类内无重复、关键符号覆盖、LRU 行为),与安卓 SymbolData.kt 逐项一致,键盘/语音模式共用。
enum SymbolData {

    struct Category {
        let id: String
        let items: [String]
    }

    static let recentID = "recent"

    /// 9 宫格 1 键(@#)的固定高频符号候选(对齐豆包,顺序固定不做权重;
    /// 经 scratch-keyboard-verify/test_key1_symbols.py 验证,与安卓/鸿蒙逐项一致)。
    /// 括号/书名号成套:点前半且光标后无文字 → 成套插入光标居中;有文字只插前半;后半直接上屏。
    static let key1Symbols: [String] = ["#", "@", "（", "）", "*", "-", "+", "。", "～", "、", "《", "》", "/"]

    static let categories: [Category] = [
        Category(id: "zh", items: [
            "，", "。", "？", "！", "、", "；", "：", "“", "”", "‘", "’",
            "（", "）", "【", "】", "《", "》", "〈", "〉", "「", "」", "『", "』",
            "…", "—", "～", "·", "﹏", "＿", "￥"
        ]),
        Category(id: "en", items: [
            ",", ".", "?", "!", ";", ":", "'", "\"", "(", ")", "[", "]",
            "{", "}", "<", ">", "@", "#", "$", "%", "^", "&", "*", "-",
            "_", "+", "=", "/", "\\", "|", "~", "`"
        ]),
        Category(id: "bracket", items: [
            "（", "）", "(", ")", "［", "］", "[", "]", "｛", "｝", "{", "}",
            "〈", "〉", "《", "》", "「", "」", "『", "』", "【", "】", "〔", "〕",
            "«", "»", "‹", "›"
        ]),
        Category(id: "math", items: [
            "+", "-", "×", "÷", "=", "≠", "≈", "<", ">", "≤", "≥", "±",
            "√", "∞", "%", "‰", "°", "π", "∑", "∫", "Δ", "∈", "∪", "∩",
            "∴", "∵", "⊥", "∥", "∠", "½", "¼", "¾", "²", "³"
        ]),
        Category(id: "num", items: [
            "①", "②", "③", "④", "⑤", "⑥", "⑦", "⑧", "⑨", "⑩",
            "⑴", "⑵", "⑶", "⑷", "⑸", "⑹", "⑺", "⑻", "⑼", "⑽",
            "Ⅰ", "Ⅱ", "Ⅲ", "Ⅳ", "Ⅴ", "Ⅵ", "Ⅶ", "Ⅷ", "Ⅸ", "Ⅹ",
            "㈠", "㈡", "㈢", "㈣", "㈤"
        ]),
        Category(id: "currency", items: [
            "￥", "¥", "$", "€", "£", "¢", "₩", "₽", "₹", "฿", "₫", "₴"
        ]),
        Category(id: "arrow", items: [
            "←", "→", "↑", "↓", "↔", "↕", "↖", "↗", "↘", "↙", "⇐", "⇒",
            "★", "☆", "♥", "♡", "●", "○", "■", "□", "◆", "◇", "▲", "△",
            "※", "§", "№", "℃", "℉", "©", "®", "™"
        ])
    ]

    /// 分类标签(4 语种,自包含)。lang: zh/en/ru/ko。
    static func label(_ id: String, lang: String) -> String {
        let i: Int
        switch lang {
        case "en": i = 1
        case "ru": i = 2
        case "ko": i = 3
        default: i = 0
        }
        let table: [String: [String]] = [
            recentID: ["最近", "Recent", "Недавние", "최근"],
            "zh": ["中文", "Chinese", "Кит.", "중문"],
            "en": ["英文", "English", "Англ.", "영문"],
            "bracket": ["括号", "Brackets", "Скобки", "괄호"],
            "math": ["数学", "Math", "Матем.", "수학"],
            "num": ["序号", "Numbering", "Нумерация", "번호"],
            "currency": ["货币", "Currency", "Валюта", "통화"],
            "arrow": ["箭头", "Arrows", "Стрелки", "화살표"]
        ]
        return table[id]?[i] ?? id
    }
}
